//! Which device trees a kernel build produces: kernel configs, Yocto's
//! `KERNEL_DEVICETREE`, and the subset of make used by `arch/*/boot/dts/**/Makefile`.

use std::collections::{BTreeMap, HashMap};

use crate::vfs::{Vfs, dirname, normalize};

/// A kernel `.config` or defconfig.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Config {
    values: HashMap<String, String>,
    /// A defconfig only lists symbols that differ from their defaults, so anything it
    /// doesn't mention may still be enabled.
    pub partial: bool,
}

impl Config {
    pub fn parse(text: &str) -> Self {
        let mut values = HashMap::new();
        for line in text.lines().map(str::trim) {
            if let Some(name) = line
                .strip_prefix("# ")
                .and_then(|l| l.strip_suffix(" is not set"))
            {
                values.insert(name.to_string(), "n".to_string());
            } else if let Some((name, value)) = line.split_once('=')
                && name.starts_with("CONFIG_")
            {
                values.insert(name.to_string(), value.trim_matches('"').to_string());
            }
        }
        // A full .config is generated by Kconfig and says so.
        let partial = !text.contains("Automatically generated file");
        Config { values, partial }
    }

    pub fn len(&self) -> usize {
        self.values.len()
    }

    pub fn is_empty(&self) -> bool {
        self.values.is_empty()
    }

    /// The value make sees for `$(CONFIG_X)`: empty when unset or `n`.
    pub fn value(&self, name: &str) -> &str {
        match self.values.get(name).map(String::as_str) {
            Some("n") | None => "",
            Some(v) => v,
        }
    }

    pub fn enabled(&self, name: &str) -> bool {
        matches!(self.value(name), "y" | "m")
    }

    /// The architecture (`arch/<name>`) this config is for. A full `.config` sets the arch
    /// symbol; a defconfig often leaves it at its default, so arch-only symbols decide.
    pub fn arch(&self) -> Option<&'static str> {
        const ARCHES: [(&str, &str); 6] = [
            ("CONFIG_ARM64", "arm64"),
            ("CONFIG_RISCV", "riscv"),
            ("CONFIG_ARM", "arm"),
            ("CONFIG_X86", "x86"),
            ("CONFIG_MIPS", "mips"),
            ("CONFIG_PPC", "powerpc"),
        ];
        if let Some((_, arch)) = ARCHES.iter().find(|(sym, _)| self.enabled(sym)) {
            return Some(arch);
        }
        let any_with = |prefix: &str| self.values.keys().any(|k| k.starts_with(prefix));
        if any_with("CONFIG_ARM64_") {
            Some("arm64")
        } else if any_with("CONFIG_RISCV_") {
            Some("riscv")
        } else if any_with("CONFIG_ARCH_MULTI_V") || any_with("CONFIG_CPU_V7") {
            Some("arm")
        } else {
            None
        }
    }
}

/// The device trees a Yocto build installs: `KERNEL_DEVICETREE` from `local.conf`, a machine
/// `.conf`, or `bitbake -e` output. `None` if the text doesn't set it.
pub fn kernel_devicetree(text: &str) -> Option<Vec<String>> {
    // Join line continuations first.
    let joined = text.replace("\\\n", " ");
    let mut found = false;
    let mut list: Vec<String> = Vec::new();
    for line in joined.lines().map(str::trim) {
        let Some(rest) = line.strip_prefix("KERNEL_DEVICETREE") else {
            continue;
        };
        let (op, value) = [
            ":append", ":prepend", "_append", "_prepend", "??=", "?=", "+=", "=+", ":=", "=",
        ]
        .iter()
        .find_map(|op| {
            let r = rest.trim_start().strip_prefix(op)?;
            // `:append` and friends are followed by an `=`.
            let r = if op.starts_with([':', '_']) {
                r.trim_start().strip_prefix('=')?
            } else {
                r
            };
            Some((*op, r))
        })?;
        let value = value.trim().trim_matches(['"', '\'']);
        let words = value.split_whitespace().map(str::to_string);
        found = true;
        match op {
            "=" | ":=" => list = words.collect(),
            "?=" | "??=" if !list.is_empty() => {}
            "?=" | "??=" => list = words.collect(),
            ":prepend" | "_prepend" | "=+" => {
                let mut new: Vec<String> = words.collect();
                new.extend(list);
                list = new;
            }
            _ => list.extend(words),
        }
    }
    found.then_some(list)
}

/// One target a dts Makefile can build.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DtbTarget {
    /// The `.dtb`/`.dtbo` path in the VFS.
    pub dtb: String,
    /// Source for plain targets (`.dts`/`.dtso`); for composites, the base's source.
    pub source: String,
    /// `CONFIG_` symbols gating it (its Makefile line and any gated parent `subdir`).
    pub symbols: Vec<String>,
    /// Whether the given config builds it; `None` without a config.
    pub built: Option<bool>,
    /// For `name-dtbs := base.dtb x.dtbo …`: the component `.dtb`/`.dtbo` paths.
    pub composite: Option<Vec<String>>,
    /// Built with `dtc -@` (`DTC_FLAGS` / `DTC_FLAGS_<name>`).
    pub symbols_flag: bool,
}

/// What the dts Makefiles say about the boards in a source tree.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Kbuild {
    pub targets: Vec<DtbTarget>,
    /// Constructs that couldn't be evaluated (and were skipped).
    pub warnings: Vec<String>,
    /// The architecture the config is for, and whether it was inferred from the Makefiles
    /// (a defconfig often doesn't name it).
    pub arch: Option<(String, bool)>,
}

impl Kbuild {
    pub fn for_source(&self, source: &str) -> Option<&DtbTarget> {
        self.targets
            .iter()
            .find(|t| t.source == source && t.composite.is_none())
    }
}

/// What builds the boards in `vfs`: `config` evaluates the Makefiles' `CONFIG_` gates;
/// `yocto` (a `KERNEL_DEVICETREE` list) names the built targets directly.
pub fn evaluate(vfs: &dyn Vfs, config: Option<&Config>, yocto: Option<&[String]>) -> Kbuild {
    let makefiles: Vec<&str> = vfs
        .paths()
        .filter(|p| p.ends_with("/Makefile") && p.contains("/boot/dts/"))
        .collect();
    let mut out = Kbuild::default();

    // Gates from parents' `subdir-$(CONFIG_X) += child`.
    let mut parsed: BTreeMap<String, Parsed> = BTreeMap::new();
    for mf in &makefiles {
        let text = String::from_utf8_lossy(&vfs.read(mf).unwrap_or_default()).into_owned();
        let p = parse_makefile(&text, config, &mut out.warnings, mf);
        parsed.insert(dirname(mf).to_string(), p);
    }
    let mut dir_gates: HashMap<String, Vec<String>> = HashMap::new();
    for (dir, p) in &parsed {
        for (child, gates) in &p.subdirs {
            dir_gates.insert(normalize(&format!("{dir}/{child}")), gates.clone());
        }
    }
    let gates_of = |dir: &str| -> Vec<String> {
        let mut gates = Vec::new();
        let mut cur = dir.to_string();
        while let Some(g) = dir_gates.get(&cur) {
            gates.extend(g.iter().cloned());
            cur = dirname(&cur).to_string();
        }
        gates
    };

    // The config's architecture: named by the config, or else the arch whose Makefiles use
    // the most of its enabled symbols (arm and arm64 share most platform symbols, but each
    // config enables some only its own arch uses).
    let arch_of = |dir: &str| {
        // `arch/<name>/…`, at the start of the path or after a mount prefix.
        let rest = dir
            .strip_prefix("arch/")
            .or_else(|| dir.split_once("/arch/").map(|(_, r)| r))?;
        rest.split('/').next().map(str::to_string)
    };
    out.arch = config.and_then(|c| {
        if let Some(a) = c.arch() {
            return Some((a.to_string(), false));
        }
        let mut score: HashMap<String, usize> = HashMap::new();
        let mut seen: std::collections::HashSet<(String, String)> =
            std::collections::HashSet::new();
        for (dir, p) in &parsed {
            let Some(arch) = arch_of(dir) else { continue };
            for (_, gates) in p.dtbs.iter().chain(&p.subdirs) {
                for g in gates.iter().filter(|g| c.enabled(g)) {
                    if seen.insert((arch.clone(), g.clone())) {
                        *score.entry(arch.clone()).or_default() += 1;
                    }
                }
            }
        }
        let mut ranked: Vec<(String, usize)> = score.into_iter().collect();
        ranked.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
        match ranked.as_slice() {
            [(best, n), (_, m), ..] if n > m => Some((best.clone(), true)),
            [(best, _)] => Some((best.clone(), true)),
            _ => None,
        }
    });

    for (dir, p) in &parsed {
        let parent_gates = gates_of(dir);
        for (target, gates) in &p.dtbs {
            let dtb = normalize(&format!("{dir}/{target}"));
            let stem = target.rsplit('/').next().unwrap_or(target);
            let stem = stem.rsplit_once('.').map_or(stem, |(s, _)| s);
            let composite = p.composites.get(stem).map(|parts| {
                parts
                    .iter()
                    .map(|c| normalize(&format!("{dir}/{c}")))
                    .collect::<Vec<_>>()
            });
            let source_of = |dtb: &str| match dtb.strip_suffix(".dtbo") {
                Some(base) => format!("{base}.dtso"),
                None => format!("{}.dts", dtb.strip_suffix(".dtb").unwrap_or(dtb)),
            };
            let source = match &composite {
                Some(parts) => parts.first().map(|b| source_of(b)).unwrap_or_default(),
                None => source_of(&dtb),
            };
            let mut symbols = parent_gates.clone();
            symbols.extend(gates.iter().cloned());
            symbols.dedup();
            let built = if let Some(list) = yocto {
                // Entries are paths under boot/dts (`vendor/board.dtb`), or bare file names.
                let rel = dtb.split("/boot/dts/").nth(1).unwrap_or(&dtb);
                let file = dtb.rsplit('/').next().unwrap_or(&dtb);
                Some(
                    list.iter()
                        .any(|y| y == rel || (!y.contains('/') && y == file)),
                )
            } else {
                // A config only builds its own architecture's device trees.
                let arch_ok = out.arch.as_ref().is_none_or(|(a, _)| {
                    let marker = format!("arch/{a}/boot/dts/");
                    dtb.starts_with(&marker) || dtb.contains(&format!("/{marker}"))
                });
                config.map(|c| arch_ok && symbols.iter().all(|s| c.enabled(s)))
            };
            let symbols_flag = p.symbols_all || p.symbols_for.iter().any(|n| n == stem);
            out.targets.push(DtbTarget {
                dtb,
                source,
                symbols,
                built,
                composite,
                symbols_flag,
            });
        }
    }
    out
}

#[derive(Default)]
struct Parsed {
    /// Target (relative to the Makefile) and the `CONFIG_` symbols gating its line.
    dtbs: Vec<(String, Vec<String>)>,
    subdirs: Vec<(String, Vec<String>)>,
    composites: HashMap<String, Vec<String>>,
    symbols_all: bool,
    symbols_for: Vec<String>,
}

/// Expands `$(VAR)` / `${VAR}`: make variables, then config symbols. Unsupported functions
/// expand to nothing (with a warning).
fn expand(
    text: &str,
    vars: &HashMap<String, String>,
    config: Option<&Config>,
    warn: &mut Vec<String>,
    at: &str,
) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(i) = rest.find('$') {
        out.push_str(&rest[..i]);
        let after = &rest[i + 1..];
        let close = match after.chars().next() {
            Some('(') => ')',
            Some('{') => '}',
            _ => {
                out.push('$');
                rest = after;
                continue;
            }
        };
        let Some(end) = after.find(close) else {
            out.push_str(&rest[i..]);
            break;
        };
        let name = &after[1..end];
        if name.contains(' ') || name.contains(',') {
            warn.push(format!("{at}: skipped unsupported make function $({name})"));
        } else if let Some(v) = vars.get(name) {
            out.push_str(v);
        } else if let Some(c) = config {
            out.push_str(c.value(name));
        }
        rest = &after[end + 1..];
    }
    out.push_str(rest);
    out
}

/// The `CONFIG_` symbol in a `dtb-$(CONFIG_X)` / `subdir-${CONFIG_X}` suffix, or `y`/`m`/``.
fn gate(suffix: &str) -> Result<Vec<String>, ()> {
    let inner = suffix
        .strip_prefix("$(")
        .and_then(|s| s.strip_suffix(')'))
        .or_else(|| suffix.strip_prefix("${").and_then(|s| s.strip_suffix('}')));
    match (inner, suffix) {
        (Some(sym), _) => Ok(vec![sym.to_string()]),
        (None, "y" | "m") => Ok(Vec::new()),
        // `dtb- +=` (an empty or unset symbol): never built.
        _ => Err(()),
    }
}

fn parse_makefile(text: &str, config: Option<&Config>, warn: &mut Vec<String>, at: &str) -> Parsed {
    let mut p = Parsed::default();
    let mut vars: HashMap<String, String> = HashMap::new();
    // Each level: (active, a branch has been taken).
    let mut conds: Vec<(bool, bool)> = Vec::new();
    let joined = text.replace("\\\r\n", " ").replace("\\\n", " ");
    for raw in joined.lines() {
        let line = raw.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let active = conds.iter().all(|c| c.0);
        let word = line.split_whitespace().next().unwrap_or("");
        match word {
            "ifeq" | "ifneq" | "ifdef" | "ifndef" => {
                let args = line[word.len()..].trim();
                let truth = match config {
                    None => true, // without a config, assume everything may be built
                    Some(_) if word.starts_with("ifdef") || word.starts_with("ifndef") => {
                        let v = expand(&format!("$({args})"), &vars, config, warn, at);
                        (word == "ifdef") == !v.is_empty()
                    }
                    Some(_) => {
                        let inner = args.trim_start_matches('(').trim_end_matches(')');
                        let (a, b) = inner.split_once(',').unwrap_or((inner, ""));
                        let a = expand(a.trim().trim_matches(['"', '\'']), &vars, config, warn, at);
                        let b = expand(b.trim().trim_matches(['"', '\'']), &vars, config, warn, at);
                        (word == "ifeq") == (a.trim() == b.trim())
                    }
                };
                conds.push((truth, truth));
                continue;
            }
            "else" => {
                if let Some(c) = conds.last_mut() {
                    c.0 = !c.1;
                    c.1 = true;
                }
                continue;
            }
            "endif" => {
                conds.pop();
                continue;
            }
            "include" | "-include" => {
                warn.push(format!("{at}: skipped `{line}`"));
                continue;
            }
            _ => {}
        }
        if !active {
            continue;
        }
        let Some((lhs, op, rhs)) = ["::=", ":=", "+=", "?=", "="].iter().find_map(|op| {
            let i = line.find(op)?;
            Some((line[..i].trim(), *op, line[i + op.len()..].trim()))
        }) else {
            continue;
        };
        let value = expand(rhs, &vars, config, warn, at);
        let words = || value.split_whitespace().map(str::to_string);
        if let Some(suffix) = lhs.strip_prefix("dtb-") {
            if let Ok(gates) = gate(suffix) {
                p.dtbs.extend(words().map(|w| (w, gates.clone())));
            }
        } else if let Some(suffix) = lhs.strip_prefix("subdir-") {
            if let Ok(gates) = gate(suffix) {
                p.subdirs
                    .extend(words().map(|w| (w.trim_end_matches('/').to_string(), gates.clone())));
            }
        } else if let Some(name) = lhs.strip_suffix("-dtbs") {
            let entry = p.composites.entry(name.to_string()).or_default();
            if op != "+=" {
                entry.clear();
            }
            entry.extend(words());
        } else if lhs == "DTC_FLAGS" {
            p.symbols_all |= value.split_whitespace().any(|w| w == "-@");
        } else if let Some(name) = lhs.strip_prefix("DTC_FLAGS_") {
            if value.split_whitespace().any(|w| w == "-@") {
                p.symbols_for.push(name.to_string());
            }
        } else {
            let name = lhs.to_string();
            match op {
                "+=" => {
                    let v = vars.entry(name).or_default();
                    if !v.is_empty() {
                        v.push(' ');
                    }
                    v.push_str(&value);
                }
                "?=" => {
                    vars.entry(name).or_insert(value);
                }
                _ => {
                    vars.insert(name, value);
                }
            }
        }
    }
    p
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::vfs::MemVfs;

    fn tree() -> MemVfs {
        MemVfs::new()
            .with("k/arch/arm64/boot/dts/Makefile", "subdir-y += acme\nsubdir-$(CONFIG_ARCH_FOO) += foo\n")
            .with(
                "k/arch/arm64/boot/dts/acme/Makefile",
                "# SPDX\ndtb-$(CONFIG_ARCH_ACME) += acme-a.dtb \\\n\tacme-b.dtb\ndtb-${CONFIG_ACME_EXTRA} += acme-c.dtb\n\
                 dtb-y += acme-always.dtb\ndtb- += acme-never.dtb\n\
                 DTC_FLAGS_acme-a := -@\n\
                 acme-a-cam-dtbs := acme-a.dtb \\\n\tacme-cam.dtbo\ndtb-$(CONFIG_ARCH_ACME) += acme-cam.dtbo acme-a-cam.dtb\n\
                 BOARDS := acme-v1.dtb\nBOARDS += acme-v2.dtb\ndtb-$(CONFIG_ARCH_ACME) += $(BOARDS)\n\
                 ifeq ($(CONFIG_ACME_EXTRA),y)\ndtb-y += acme-extra-only.dtb\nelse\ndtb-y += acme-no-extra.dtb\nendif\n",
            )
            .with("k/arch/arm64/boot/dts/foo/Makefile", "dtb-y += foo.dtb\n")
    }

    fn built(k: &Kbuild) -> Vec<&str> {
        let mut v: Vec<&str> = k
            .targets
            .iter()
            .filter(|t| t.built == Some(true))
            .map(|t| t.dtb.rsplit('/').next().unwrap())
            .collect();
        v.sort();
        v
    }

    #[test]
    fn config_parsing() {
        let c = Config::parse(
            "#\n# Automatically generated file; DO NOT EDIT.\nCONFIG_A=y\nCONFIG_B=m\n# CONFIG_C is not set\nCONFIG_S=\"x\"\n",
        );
        assert!(
            c.enabled("CONFIG_A")
                && c.enabled("CONFIG_B")
                && !c.enabled("CONFIG_C")
                && !c.enabled("CONFIG_D")
        );
        assert_eq!(c.value("CONFIG_S"), "x");
        assert!(!c.partial);
        assert!(Config::parse("CONFIG_A=y\n").partial, "defconfig");
    }

    #[test]
    fn makefiles_with_and_without_config() {
        let vfs = tree();
        let all = evaluate(&vfs, None, None);
        assert!(all.targets.iter().all(|t| t.built.is_none()));
        let a = all
            .targets
            .iter()
            .find(|t| t.dtb.ends_with("acme-a.dtb"))
            .unwrap();
        assert_eq!(a.source, "k/arch/arm64/boot/dts/acme/acme-a.dts");
        assert_eq!(a.symbols, ["CONFIG_ARCH_ACME"]);
        assert!(a.symbols_flag);
        let cam = all
            .targets
            .iter()
            .find(|t| t.dtb.ends_with("acme-a-cam.dtb"))
            .unwrap();
        assert_eq!(cam.source, "k/arch/arm64/boot/dts/acme/acme-a.dts");
        assert_eq!(cam.composite.as_ref().unwrap().len(), 2);
        let overlay = all
            .targets
            .iter()
            .find(|t| t.dtb.ends_with("acme-cam.dtbo"))
            .unwrap();
        assert_eq!(overlay.source, "k/arch/arm64/boot/dts/acme/acme-cam.dtso");
        assert!(
            !all.targets
                .iter()
                .any(|t| t.dtb.ends_with("acme-never.dtb"))
        );
        let foo = all
            .targets
            .iter()
            .find(|t| t.dtb.ends_with("foo.dtb"))
            .unwrap();
        assert_eq!(
            foo.symbols,
            ["CONFIG_ARCH_FOO"],
            "gated by the parent's subdir line"
        );

        let cfg = Config::parse("CONFIG_ARCH_ACME=y\n");
        let k = evaluate(&vfs, Some(&cfg), None);
        assert_eq!(
            built(&k),
            [
                "acme-a-cam.dtb",
                "acme-a.dtb",
                "acme-always.dtb",
                "acme-b.dtb",
                "acme-cam.dtbo",
                "acme-no-extra.dtb",
                "acme-v1.dtb",
                "acme-v2.dtb"
            ]
        );
        let cfg = Config::parse("CONFIG_ACME_EXTRA=y\nCONFIG_ARCH_FOO=y\n");
        let k = evaluate(&vfs, Some(&cfg), None);
        assert_eq!(
            built(&k),
            [
                "acme-always.dtb",
                "acme-c.dtb",
                "acme-extra-only.dtb",
                "foo.dtb"
            ]
        );
    }

    #[test]
    fn config_architecture() {
        assert_eq!(Config::parse("CONFIG_ARM64=y\n").arch(), Some("arm64"));
        assert_eq!(
            Config::parse("CONFIG_ARM64_VA_BITS_48=y\nCONFIG_ARCH_ROCKCHIP=y\n").arch(),
            Some("arm64")
        );
        assert_eq!(
            Config::parse("CONFIG_ARCH_MULTI_V7=y\n").arch(),
            Some("arm")
        );
        assert_eq!(Config::parse("CONFIG_ARCH_ROCKCHIP=y\n").arch(), None);

        let vfs = MemVfs::new()
            .with(
                "k/arch/arm64/boot/dts/r/Makefile",
                "dtb-$(CONFIG_ARCH_R) += a64.dtb\n",
            )
            .with(
                "k/arch/arm/boot/dts/r/Makefile",
                "dtb-$(CONFIG_ARCH_R) += a32.dtb\n",
            );
        let k = evaluate(
            &vfs,
            Some(&Config::parse("CONFIG_ARM64=y\nCONFIG_ARCH_R=y\n")),
            None,
        );
        assert_eq!(built(&k), ["a64.dtb"]);
        assert_eq!(k.arch, Some(("arm64".into(), false)));

        // No arch symbol: inferred from which arch's Makefiles use the enabled symbols.
        let vfs = vfs.with(
            "k/arch/arm64/boot/dts/only64/Makefile",
            "dtb-$(CONFIG_ARCH_ONLY64) += x.dtb\n",
        );
        let k = evaluate(
            &vfs,
            Some(&Config::parse("CONFIG_ARCH_R=y\nCONFIG_ARCH_ONLY64=y\n")),
            None,
        );
        assert_eq!(k.arch, Some(("arm64".into(), true)));
        assert_eq!(built(&k), ["a64.dtb", "x.dtb"]);
    }

    #[test]
    fn yocto_kernel_devicetree() {
        let conf = "MACHINE ??= \"x\"\nKERNEL_DEVICETREE = \"acme/acme-a.dtb \\\n  acme/acme-cam.dtbo\"\nKERNEL_DEVICETREE:append = \" acme/acme-b.dtb\"\n";
        let list = kernel_devicetree(conf).unwrap();
        assert_eq!(
            list,
            ["acme/acme-a.dtb", "acme/acme-cam.dtbo", "acme/acme-b.dtb"]
        );
        assert!(kernel_devicetree("MACHINE = \"x\"\n").is_none());
        let k = evaluate(&tree(), None, Some(&list));
        assert_eq!(built(&k), ["acme-a.dtb", "acme-b.dtb", "acme-cam.dtbo"]);
    }
}
